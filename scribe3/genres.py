def seed_genre_pack(store, pack_name: str) -> None:
    """把可选题材包 pack_name 的 keep_list/cliches 落进 per-work craft_rule 表。

    keep_list → allow_pattern(前置 skip 判定,减法,别删清单);
    cliches   → purple_regex(反面词表,套路桥段命中即报,不作生成模板)。

    幂等:同 note 标记的规则已存在则跳过该批次,重复调用不产生重复行。
    未知 pack_name → ValueError。

    默认不调用:store.seed_craft_rules()(首书乱世铜炉种子)不引用本函数,
    题材包永远是显式 opt-in——scribe3 严肃/志怪定位,防止爽文向拉回。
    """
    if pack_name not in GENRE_PACKS:
        raise ValueError(
            f"未知题材包 '{pack_name}'(合法: {sorted(GENRE_PACKS)})")

    pack = GENRE_PACKS[pack_name]
    name = pack["name"]
    keep_note = f"题材包:{name} 别删清单"
    cliche_note = f"题材包:{name} 套路反面"

    existing_notes = {r.get("note", "") for r in store.list_craft_rules()}

    if keep_note not in existing_notes:
        for pattern in pack["keep_list"]:
            store.add_craft_rule("allow_pattern", pattern, keep_note)

    if cliche_note not in existing_notes:
        for pattern in pack["cliches"]:
            store.add_craft_rule("purple_regex", pattern, cliche_note)
