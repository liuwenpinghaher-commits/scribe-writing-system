// 长程扩写不能继承任何旧验收书的角色、设定或文风指令。具体叙事事实由写作链路
// 从当前 work 的正典、知识帧、章计划和已定稿正文装配；这里只声明跨作品不变的质量约束。
export function buildLongformDraftPrompt({ seq, brief, minLen }) {
  return [
    `请直接写第${seq}章完整正文草稿（${brief}）。`,
    `务必用提案卡交付，目标约${minLen}字以上中文正文。`,
    '仅使用当前作品已批准的章计划、世界状态、知识帧与前章定稿作为叙事依据。',
    '严格遵守当前焦点人物的限知边界，不引入其他验收书的人物、地点、专名或规则。',
    '以动作、感官、选择与后果推进完整场景；不替作者裁决道德；承接前章并保持与质量合同一致。',
  ].join('')
}
