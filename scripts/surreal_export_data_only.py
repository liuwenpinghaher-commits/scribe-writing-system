#!/usr/bin/env python3
"""从 Surreal 3.x export .surql 抽出「仅数据」脚本（跳过 DEFINE schema）。

用于两阶段恢复：先 apply_schema，再 import 本文件，避免 export 自带的
不完整 SCHEMAFULL 与运行时 migration 冲突。

  python3 scripts/surreal_export_data_only.py in.surql -o out_data.surql
  python3 scripts/surreal_export_data_only.py in.surql --skip-tables _migration
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

_TABLE_HDR = re.compile(r"^--\s*TABLE(?:\s+DATA)?\s*:\s*(\S+)")
_DATA_HDR = re.compile(r"^--\s*TABLE DATA\s*:\s*(\S+)", re.I)


def extract_data_only(
    text: str,
    *,
    skip_tables: set[str] | None = None,
) -> str:
    skip = {s.lower() for s in (skip_tables or set())}
    lines = text.splitlines()
    out: list[str] = [
        "-- generated by surreal_export_data_only.py",
        "-- schema must already exist (e.g. scribe3 apply_schema)",
        "OPTION IMPORT;",
        "",
    ]
    in_data = False
    current_table: str | None = None
    buf: list[str] = []

    def flush() -> None:
        nonlocal buf, current_table
        if not buf or not current_table:
            buf = []
            return
        if current_table.lower() in skip:
            buf = []
            return
        out.append(f"-- TABLE DATA: {current_table}")
        out.extend(buf)
        out.append("")
        buf = []

    for line in lines:
        m_data = _DATA_HDR.match(line.strip()) if line.strip().startswith("--") else None
        if m_data:
            flush()
            in_data = True
            current_table = m_data.group(1).rstrip()
            continue
        # next table schema section ends data block
        if line.startswith("-- TABLE:") or line.startswith("-- ------------------------------"):
            # only end data when we see a new TABLE (not TABLE DATA) header later
            pass
        if line.startswith("-- TABLE:") and "DATA" not in line.upper():
            flush()
            in_data = False
            current_table = None
            continue
        if line.startswith("-- ANALYZERS") or line.startswith("-- INDEXES") or line.startswith("-- FUNCTIONS"):
            flush()
            in_data = False
            current_table = None
            continue
        if in_data:
            # skip DEFINE if any leaked
            if line.strip().startswith("DEFINE "):
                continue
            buf.append(line)

    flush()
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("input", type=Path)
    p.add_argument("-o", "--output", type=Path, required=True)
    p.add_argument(
        "--skip-tables",
        default="_migration",
        help="comma-separated table names to skip (default: _migration)",
    )
    args = p.parse_args(argv)
    skip = {s.strip() for s in args.skip_tables.split(",") if s.strip()}
    text = args.input.read_text(encoding="utf-8", errors="replace")
    out = extract_data_only(text, skip_tables=skip)
    args.output.write_text(out, encoding="utf-8")
    n_ins = out.count("INSERT ")
    print(f"wrote {args.output} bytes={args.output.stat().st_size} insert_blocks~={n_ins}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
