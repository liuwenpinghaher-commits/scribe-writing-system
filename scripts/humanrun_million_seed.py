def _assert_floors():
    assert WORD_GOAL == 1_000_000
    assert cn_len(NORTH_STAR) >= 20
    for c in CHARS:
        assert cn_len(c["personality_detail"]) >= 200, c["name"]
        assert cn_len(c["backstory"]) >= 200, c["name"]
        for k in ("surface_goal", "deep_need", "fear", "internal_conflict"):
            assert cn_len(c[k]) >= 80, (c["name"], k, cn_len(c[k]))
    for m in MOTIFS:
        assert cn_len(m["theme"]) >= 36, m["name"]
        assert cn_len(m["unfolding"]) >= 50, m["name"]
    for ch in CHAPTERS:
        assert cn_len(ch["synopsis"]) >= 36, ch["title"]
    syns = [ch["synopsis"][:20] for ch in CHAPTERS]
    assert len(set(syns)) == len(syns), "梗概开头不得互抄"
    assert len(VOLUMES) == 4
    assert len(CHAPTERS) == 12
    for v in VOLUMES:
        assert cn_len(v["intro"]) >= 280, v["title"]
        assert "十二章十二笔" not in v["intro"]
        assert "不一次生成" not in v["intro"]
        assert "近窗" not in v["intro"]
    places = (
        "七号院", "粮市", "西郊", "埠头", "青石埠", "庙会", "义庄",
        "结年", "醒库", "渡船", "田",
    )
    for v in VOLUMES:
        n = sum(1 for p in places if p in v["intro"])
        assert n >= 3, (v["title"], n)


_assert_floors()
