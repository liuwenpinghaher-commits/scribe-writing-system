_COMPILED = [(rid, re.compile(pat), sev, desc) for rid, pat, sev, desc in RULES]


def detect(text: str) -> list[dict]:
    """返回命中列表:[{rule, severity, desc, match, pos}]。"""
    hits: list[dict] = []
    for rid, rx, sev, desc in _COMPILED:
        for m in rx.finditer(text):
            hits.append({"rule": rid, "severity": sev, "desc": desc,
                         "match": m.group(0), "pos": m.start()})
    return hits


def slop_density(text: str) -> float:
    """每千字命中数(工程6 的 AI 腔密度指标 Q1 的可机检代理)。"""
    n = max(1, len(text))
    return len(detect(text)) / n * 1000.0


# C1-4 生成时反趋均值约束块(注入写作 prompt;内核3 §3.3:在生成内部约束,而非事后补救)
CONSTRAINT_BLOCK = (
    "【文学约束·写作时必须遵守(反 AI 腔/反趋均值)】\n"
    "1. show 不 tell:用动作/感官/细节呈现情绪,禁止「他感到悲伤/愤怒/绝望」式直说。\n"
    "2. 克制:不写顿悟升华尾句、不写「总而言之/这一刻他明白了」;让画面收尾,把判断留给读者。\n"
    "3. 意外性:每段至少一处不落俗套——期望反转、代价放大、或信息不对称;拒绝可预测的顺滑。\n"
    "4. 具体优先:用专有的物、动作、数字,替代「一抹弧度/一丝寒意/五味杂陈」这类通用模板。\n"
    "5. 禁用清单(出现即视为失败):嘴角勾起一抹弧度、眼底闪过一丝、一股暖流涌上心头、"
    "命运的齿轮、空气仿佛凝固、千言万语化作、…般的存在、值得一提的是。\n"
    "6. 节奏:长短句交错,避免连续同构句;副词(缓缓/轻轻/微微)整段不超过 1 次。"
)


def constraint_block() -> str:
    return CONSTRAINT_BLOCK


def auto_fix_prompt(text: str) -> str | None:
    """若 AI 腔密度过高,产出一段让模型自我修复的 prompt;否则 None(不必修)。"""
    hits = detect(text)
    high = [h for h in hits if h["severity"] == "high"]
    if not high and slop_density(text) < 3.0:
        return None
    bad = "、".join(sorted({h["match"] for h in hits})[:12])
    return (
        "下面这段正文有 AI 腔/套路化表达。请在保留情节与信息不变的前提下重写,"
        f"消除这些套路:{bad}。要求 show 不 tell、克制、具体。只输出重写后的正文。\n\n" + text
    )


def build_llm_check_prompt(text: str) -> str:
    """LLM 语义二检 prompt(正则查不出的隐性 AI 腔:空洞、均值化、缺意外性)。
    返回让模型输出 JSON 的指令;由调用方送入 LLM 并解析。"""
    return (
        "你是严苛的文学编辑。判断下面这段中文小说正文是否有「AI 腔/趋均值」问题"
        "(空泛抒情、套路比喻、缺乏意外性、show 不足)。\n"
        '只输出一行 JSON:{"slop":true|false,"reasons":["..."],"worst":"最突出的一处原文"}。\n\n'
        + text
    )
